"""Rebuild IrisI's vector identity and launcher PNGs using Python's standard library.

Run from any directory: python design/generate_brand_assets.py
Geometry is shared by SVG, Android VectorDrawable and supersampled legacy PNGs.
The mark is an optical bloom: nine curved folds around a small pupil.
"""

from pathlib import Path
import math
import struct
import zlib

ROOT = Path(__file__).resolve().parents[1]
RES = ROOT / "app/src/main/res"
BRAND = ROOT / "docs/brand"
BACKGROUND = "#12151A"
COLORS = ("#F1D2A2", "#E6B373", "#CE9150", "#B8753D", "#C5874C", "#DEAD71", "#F3D3A5", "#F9E8CB", "#ECD0A4")


def rotate(x, y, angle):
    angle = math.radians(angle)
    return 54 + (x - 54) * math.cos(angle) - (y - 54) * math.sin(angle), 54 + (x - 54) * math.sin(angle) + (y - 54) * math.cos(angle)


def petals():
    # Separate curved petals with a soft asymmetry, not a continuous shutter ring.
    curves = (((52, 50), (45, 42), (44, 30), (52, 22)),
              ((52, 22), (59, 29), (63, 40), (57, 49)),
              ((57, 49), (55, 51), (53, 51), (52, 50)))
    for index in range(9):
        points = []
        for (a, b, c, d) in curves:
            for step in range(32):
                t = step / 32
                u = 1 - t
                x = u ** 3 * a[0] + 3 * u ** 2 * t * b[0] + 3 * u * t ** 2 * c[0] + t ** 3 * d[0]
                y = u ** 3 * a[1] + 3 * u ** 2 * t * b[1] + 3 * u * t ** 2 * c[1] + t ** 3 * d[1]
                points.append(rotate(x, y, index * 40))
        yield points


def petal_path(index):
    def p(x, y):
        x, y = rotate(x, y, index * 40)
        return f"{x:.3f},{y:.3f}"
    return (f'M{p(52, 50)} C{p(45, 42)} {p(44, 30)} {p(52, 22)} '
            f'C{p(59, 29)} {p(63, 40)} {p(57, 49)} C{p(55, 51)} {p(53, 51)} {p(52, 50)} Z')


def vector(monochrome=False):
    paths = []
    for index, color in enumerate(COLORS):
        if monochrome:
            paths.append(f'    <path android:fillColor="#FFFFFF" android:pathData="{petal_path(index)}" />')
        else:
            start, end = rotate(54, 25, index * 40), rotate(59, 45, index * 40)
            dark = shade(color, .67)
            paths.append(f'''    <path android:pathData="{petal_path(index)}">
        <aapt:attr name="android:fillColor">
            <gradient android:type="linear" android:startX="{start[0]:.3f}" android:startY="{start[1]:.3f}"
                android:endX="{end[0]:.3f}" android:endY="{end[1]:.3f}"
                android:startColor="{color}" android:endColor="{dark}" />
        </aapt:attr>
    </path>''')
    if monochrome:
        paths.insert(0, '    <group><clip-path android:fillType="evenOdd" android:pathData="M0,0 H108 V108 H0 Z M54,43 A11,11 0 1,0 54,65 A11,11 0 1,0 54,43 Z" />')
        paths.append('    </group>')
    else:
        paths.append('    <path android:fillColor="#12151A" android:pathData="M54,43 A11,11 0 1,0 54,65 A11,11 0 1,0 54,43 Z" />')
        paths.append('    <path android:fillColor="#F9E8CB" android:pathData="M49.6,48.2 A2.1,1.4 0 1,0 53.8,48.2 A2.1,1.4 0 1,0 49.6,48.2 Z" />')
    return ('<?xml version="1.0" encoding="utf-8"?>\n'
            '<!-- Generated by design/generate_brand_assets.py; organic optical iris, not a shutter aperture. -->\n'
            '<vector xmlns:android="http://schemas.android.com/apk/res/android" xmlns:aapt="http://schemas.android.com/aapt"\n'
            '    android:width="108dp" android:height="108dp"\n'
            '    android:viewportWidth="108" android:viewportHeight="108">\n'
            + '\n'.join(paths) + '\n</vector>\n')


def svg_paths(monochrome=False):
    if monochrome:
        return ('<defs><clipPath id="pupil"><path clip-rule="evenodd" d="M0,0 H108 V108 H0 Z M54,43 A11,11 0 1 0 54,65 A11,11 0 1 0 54,43 Z"/></clipPath></defs><g clip-path="url(#pupil)">'
                + "\n".join(f'<path fill="currentColor" d="{petal_path(i)}"/>' for i in range(9)) + '</g>')
    definitions = []
    paths = []
    for i, color in enumerate(COLORS):
        start, end = rotate(54, 25, i * 40), rotate(59, 45, i * 40)
        definitions.append(f'<linearGradient id="petal{i}" gradientUnits="userSpaceOnUse" x1="{start[0]}" y1="{start[1]}" x2="{end[0]}" y2="{end[1]}"><stop stop-color="{color}"/><stop offset="1" stop-color="{shade(color, .67)}"/></linearGradient>')
        paths.append(f'<path fill="url(#petal{i})" d="{petal_path(i)}"/>')
    paths.append('<path fill="#12151A" d="M54,43 A11,11 0 1 0 54,65 A11,11 0 1 0 54,43 Z"/>')
    paths.append('<ellipse fill="#F9E8CB" cx="51.7" cy="48.2" rx="2.1" ry="1.4"/>')
    return '<defs>' + ''.join(definitions) + '</defs>\n' + '\n'.join(paths)


def rgb(value):
    return tuple(int(value[i:i + 2], 16) for i in (1, 3, 5)) + (255,)


def shade(value, factor):
    return '#' + ''.join(f'{round(channel * factor):02X}' for channel in rgb(value)[:3])


def png(size, round_icon=False):
    # Scanline rasterization at 4x, followed by area downsampling. No image library.
    scale = 4
    width = size * scale
    pixels = bytearray(width * width * 4)
    for y in range(width):
        for x in range(width):
            dx, dy = abs(x + .5 - width / 2), abs(y + .5 - width / 2)
            radius = width / 2 if round_icon else width * .23
            inset = 0 if round_icon else width / 2 - radius
            inside = max(0, dx - inset) ** 2 + max(0, dy - inset) ** 2 <= radius ** 2
            if inside:
                offset = (y * width + x) * 4
                pixels[offset:offset + 4] = bytes(rgb(BACKGROUND))
    for index, (points, color) in enumerate(zip(petals(), COLORS)):
        points = [(x / 108 * width, y / 108 * width) for x, y in points]
        for y in range(width):
            scan = y + .5
            crossings = []
            for (ax, ay), (bx, by) in zip(points, points[1:] + points[:1]):
                if min(ay, by) <= scan < max(ay, by):
                    crossings.append(ax + (scan - ay) / (by - ay) * (bx - ax))
            crossings.sort()
            for left, right in zip(crossings[::2], crossings[1::2]):
                start, end = max(0, math.ceil(left - .5)), min(width, math.ceil(right - .5))
                offset = (y * width + start) * 4
                for x in range(start, end):
                    local = rotate((x + .5) * 108 / width, (y + .5) * 108 / width, -index * 40)
                    projection = ((local[0] - 54) * 8 + (local[1] - 25) * 20) / (8 ** 2 + 20 ** 2)
                    factor = 1 - .33 * max(0, min(1, projection))
                    pixel = (y * width + x) * 4
                    pixels[pixel:pixel + 4] = bytes(round(c * factor) for c in rgb(color)[:3]) + b'\xff'
    # Small pupil and glint: the colored foreground receives the graphite center;
    # the monochrome adaptive layer deliberately keeps this opening transparent.
    for y in range(width):
        for x in range(width):
            ux, uy = (x + .5) * 108 / width, (y + .5) * 108 / width
            if (ux - 54) ** 2 + (uy - 54) ** 2 <= 11 ** 2:
                pixel = (y * width + x) * 4
                pixels[pixel:pixel + 4] = bytes(rgb(BACKGROUND))
            if ((ux - 51.7) / 2.1) ** 2 + ((uy - 48.2) / 1.4) ** 2 <= 1:
                pixel = (y * width + x) * 4
                pixels[pixel:pixel + 4] = bytes(rgb("#F9E8CB"))
    raw = bytearray()
    for y in range(size):
        raw.append(0)
        for x in range(size):
            samples = [(sy * width + sx) * 4 for sy in range(y * scale, (y + 1) * scale)
                       for sx in range(x * scale, (x + 1) * scale)]
            alpha = sum(pixels[p + 3] for p in samples)
            for channel in range(3):
                raw.append(round(sum(pixels[p + channel] * pixels[p + 3] for p in samples) / alpha) if alpha else 0)
            raw.append(round(alpha / len(samples)))

    def chunk(name, data):
        return struct.pack(">I", len(data)) + name + data + struct.pack(">I", zlib.crc32(name + data))

    return (b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", struct.pack(">IIBBBBB", size, size, 8, 6, 0, 0, 0))
            + chunk(b"IDAT", zlib.compress(raw, 9)) + chunk(b"IEND", b""))


def main():
    BRAND.mkdir(parents=True, exist_ok=True)
    (RES / "drawable/ic_launcher_foreground.xml").write_text(vector(), encoding="utf-8")
    (RES / "drawable/ic_launcher_monochrome.xml").write_text(vector(True), encoding="utf-8")
    for name, monochrome in (("irisi-mark.svg", False), ("irisi-mark-mono.svg", True)):
        (BRAND / name).write_text(
            '<svg xmlns="http://www.w3.org/2000/svg" viewBox="22 22 64 64" role="img" aria-label="IrisI organic optical iris">\n'
            + svg_paths(monochrome) + '\n</svg>\n', encoding="utf-8")
    for density, size in (("mdpi", 48), ("hdpi", 72), ("xhdpi", 96), ("xxhdpi", 144), ("xxxhdpi", 192)):
        for suffix, round_icon in (("", False), ("_round", True)):
            (RES / f"mipmap-{density}/ic_launcher{suffix}.png").write_bytes(png(size, round_icon))
    (BRAND / "launcher-preview.png").write_bytes(png(512))
    print("Generated vector marks, monochrome layer, 10 launcher PNGs and preview.")


if __name__ == "__main__":
    main()
